export type Lang = 'en' | 'ar';
const dictionaries: Record<Lang, Record<DictKey, string>> = { en, ar };
const STORAGE_KEY = 'skillsync.lang';

type Ctx = { lang: Lang; dir: 'ltr' | 'rtl'; setLang: (lang: Lang) => void; t: (key: DictKey, vars?: Record<string, string | number>) => string; locale: string };
const I18nContext = createContext<Ctx | null>(null);

function initialLang(): Lang {
  try { const saved = localStorage.getItem(STORAGE_KEY); if (saved === 'ar' || saved === 'en') return saved; } catch { /* ignore */ }
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const dir = lang === 'ar' ? 'rtl' : 'ltr';
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
  }, []);
  const t = useCallback((key: DictKey, vars?: Record<string, string | number>) => {
    let text = dictionaries[lang][key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  }, [lang]);
  const value = useMemo(() => ({ lang, dir: dir as 'ltr' | 'rtl', setLang, t, locale: lang === 'ar' ? 'ar' : 'en-US' }), [lang, dir, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

export function formatDate(value: string, locale: string, fallback: string) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return fallback;
  return new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric' }).format(date);
}

export function formatTime(value: string, locale: string) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  return new Intl.DateTimeFormat(locale, { hour: 'numeric', minute: '2-digit' }).format(date);
}
